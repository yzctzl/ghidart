    private void registerName(int cid, String name) {
      if (cid > 0) {
        namesByCid.putIfAbsent(cid, name);
      }
    }

    public String nameOf(int cid) {
      String n = namesByCid.get(cid);
      return n != null ? n : "CID_" + cid;
    }

    public boolean isString(int cid) {
      return cid == string || cid == oneByteString || cid == twoByteString;
    }

