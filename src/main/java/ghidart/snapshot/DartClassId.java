    public boolean isExceptionHandlers(int cid) {
      return cid == exceptionHandlers;
    }

    public boolean isTypedDataInternal(int cid) {
      if (typedDataInt8ArrayCid <= 0 || byteDataViewCid <= 0 || typedDataCidStride <= 0) {
        return false;
      }
      return cid >= typedDataInt8ArrayCid
          && cid < byteDataViewCid
          && (cid - typedDataInt8ArrayCid) % typedDataCidStride == 0;
    }

    public boolean isTypedDataViewInternal(int cid) {
      if (cid == byteDataViewCid) return true;
      if (typedDataInt8ArrayCid <= 0 || byteDataViewCid <= 0 || typedDataCidStride <= 0) {
        return false;
      }
      return cid >= typedDataInt8ArrayCid
          && cid < byteDataViewCid
          && (cid - typedDataInt8ArrayCid) % typedDataCidStride == 1;
    }

    public boolean isTypedDataAnyRange(int cid) {
      if (typedDataInt8ArrayCid <= 0 || byteDataViewCid <= 0) {
        return false;
      }
      return cid >= typedDataInt8ArrayCid && cid < byteDataViewCid;
    }
